# One-click packaging for the pure-Python build.
# Usage:  powershell -ExecutionPolicy Bypass -File packaging\build.ps1
#         powershell -ExecutionPolicy Bypass -File packaging\build.ps1 -Version 0.2.1
#         powershell -ExecutionPolicy Bypass -File packaging\build.ps1 -Backend pyinstaller
#         powershell -ExecutionPolicy Bypass -File packaging\build.ps1 -MigrateDataFrom dist\好想跑_v0.1.1
#         powershell -ExecutionPolicy Bypass -File packaging\build.ps1 -NoDataMigration
# Output: dist/好想跑_v<version>/好想跑.exe
#         dist/haoxiangpao_v<version>_win64.zip
#         dist/haoxiangpao_v<version>_win64.sha256
#         dist/haoxiangpao_v<version>_win64_setup.exe        (NSIS, release standard)
#         dist/haoxiangpao_v<version>_win64_setup.sha256
#         dist/latest.json                  (auto-update manifest)
#
# Release assets use ASCII names on purpose: GitHub rewrites non-ASCII asset
# names, which breaks the URL recorded in latest.json.
#
# The installer is the release standard since v0.1.3.  Use -NoInstaller only
# for a quick local smoke build; a release without it is incomplete.
#
# Default backend is Nuitka standalone: modules are compiled to C and no
# replica/*.py source ships.  -Backend pyinstaller is the compatibility
# fallback; that build is much easier to unpack, so do not use it for release.
#
# Use -DownloadBaseUrl https://host/path to write absolute asset URLs; without
# it the manifest uses relative URLs (resolved against the manifest URL).
# Use -RollbackVersion '' to omit the rollback asset.  When -DownloadBaseUrl
# points at the new release, pass -RollbackBaseUrl pointing at the rollback
# tag (e.g. .../download/v0.1.4); otherwise the rollback URL is a 404.
#
# The output is versioned on purpose.  The old `dist/好想跑/` belongs to an
# existing install and may contain live data; this script never deletes it.
# If the versioned target already exists, its `data/` folder is preserved
# across a rebuild (the archive itself is built before that folder is
# restored, so live data never ends up in the zip).
#
# No JRE / unidbg runtime is copied: login and the submit path are pure Python.
param(
    [string]$Version = '',
    [string]$MigrateDataFrom = '',
    [switch]$NoDataMigration,
    [string]$DownloadBaseUrl = '',
    [string[]]$MirrorBaseUrl = @(),
    [string]$Channel = 'stable',
    [string]$RollbackVersion = '0.1.9',
    [string]$RollbackBaseUrl = '',
    [string[]]$RollbackMirrorBaseUrl = @(),
    [ValidateSet('nuitka', 'pyinstaller')]
    [string]$Backend = 'nuitka',
    [switch]$NoInstaller,
    [string]$Makensis = ''
)
$ErrorActionPreference = 'Stop'
$ROOT = Split-Path $PSScriptRoot -Parent
$NSI = Join-Path $PSScriptRoot 'installer.nsi'
$NSI_HEAD = [IO.File]::ReadAllBytes($NSI) | Select-Object -First 3
$HAS_BOM = ($NSI_HEAD.Length -eq 3) -and ($NSI_HEAD[0] -eq 0xEF) -and ($NSI_HEAD[1] -eq 0xBB) -and ($NSI_HEAD[2] -eq 0xBF)
if (-not $HAS_BOM) {
    throw 'installer.nsi must be saved as UTF-8 with BOM (EF BB BF)'
}
$DIST = Join-Path $ROOT 'dist'
$WORK = Join-Path $ROOT 'build_tmp'
$STAGE = Join-Path $ROOT 'build_stage'
$BUILT = Join-Path $STAGE '好想跑'
$EXE = Join-Path $BUILT '好想跑.exe'
$REPO = Split-Path $ROOT -Parent
$RUST = Join-Path $REPO 'rust\hxp-core'
$RUST_EXE = Join-Path $RUST 'target\release\hxp-core.exe'
$GO = Join-Path $REPO 'go\hxp-guard'
$GO_EXE = Join-Path $GO 'hxp-guard.exe'

if (-not $Version) {
    $info = Join-Path $ROOT 'replica\build_info.py'
    $match = Select-String -Path $info -Pattern "^VERSION\s*=\s*'([^']+)'" -Encoding UTF8 |
        Select-Object -First 1
    if (-not $match) { throw "Cannot read VERSION from $info" }
    $Version = $match.Matches[0].Groups[1].Value
}
$NAME = '好想跑_v' + $Version
$TARGET = Join-Path $DIST $NAME
$ARTIFACT = 'haoxiangpao_v' + $Version
$ZIP = Join-Path $DIST ($ARTIFACT + '_win64.zip')
$SETUP = Join-Path $DIST ($ARTIFACT + '_win64_setup.exe')

# Build identifier: written into replica/_build_info.py immediately before
# PyInstaller and removed afterwards.  A frozen build must not run git.
$buildInfo = Join-Path $ROOT 'replica\_build_info.py'
$commit = ''
try {
    $commit = (& git -C $ROOT rev-parse --short=7 HEAD 2>$null | Select-Object -First 1)
} catch { $commit = '' }
$dirty = $false
try {
    $dirty = [bool](& git -C $ROOT status --porcelain 2>$null)
} catch { $dirty = $false }
$builtAt = Get-Date -Format 'yyyy-MM-dd HH:mm'
$lines = @(
    '# Generated by packaging/build.ps1. Do not edit; gitignored.',
    'BUILD = {',
    ('    ''commit'': ''{0}'',' -f $commit),
    ('    ''dirty'': {0},' -f $(if ($dirty) { 'True' } else { 'False' })),
    ('    ''built_at'': ''{0}'',' -f $builtAt),
    '}',
    ''
)
[System.IO.File]::WriteAllLines(
    $buildInfo, $lines, (New-Object System.Text.UTF8Encoding($false)))
Write-Host ('== build info: {0}{1} {2} ==' -f $commit,
    $(if ($dirty) { '-dirty' } else { '' }), $builtAt)

Write-Host '== 0/5 Rust core =='
if (-not (Test-Path (Join-Path $RUST 'Cargo.toml'))) {
    throw "Rust core crate missing: $RUST"
}
Push-Location $RUST
try {
    cargo build --release --locked
    if ($LASTEXITCODE -ne 0) {
        throw "cargo build failed with exit code $LASTEXITCODE"
    }
} finally {
    Pop-Location
}
if (-not (Test-Path $RUST_EXE)) { throw "cargo did not produce $RUST_EXE" }
Write-Host ('   {0}' -f $RUST_EXE)

Write-Host '== 0/5 Go guard =='
if (-not (Test-Path (Join-Path $GO 'go.mod'))) {
    throw "Go guard module missing: $GO"
}
Push-Location $GO
try {
    go build -trimpath -ldflags='-s -w' -o $GO_EXE ./cmd/hxp-guard
    if ($LASTEXITCODE -ne 0) {
        throw "go build failed with exit code $LASTEXITCODE"
    }
} finally {
    Pop-Location
}
if (-not (Test-Path $GO_EXE)) { throw "go build did not produce $GO_EXE" }
Write-Host ('   {0}' -f $GO_EXE)

if ($Backend -eq 'nuitka') {
    Write-Host ('== 1/5 Nuitka (v{0}) ==' -f $Version)
    try {
        if (Test-Path $STAGE) { Remove-Item $STAGE -Recurse -Force }
        New-Item -ItemType Directory -Force -Path $STAGE | Out-Null
        $nuitkaArgs = @(
            '--standalone',
            '--assume-yes-for-downloads',
            '--msvc=latest',
            '--lto=yes',
            '--python-flag=no_docstrings',
            '--python-flag=no_asserts',
            '--enable-plugin=pywebview',
            '--include-module=replica._build_info',
            ('--include-data-dir=' + (Join-Path $ROOT 'frontend') + '=frontend'),
            '--include-package-data=webview',
            '--include-package-data=clr_loader',
            '--include-package-data=pythonnet',
            '--include-package-data=cv2',
            '--nofollow-import-to=pytest',
            '--nofollow-import-to=tests',
            '--nofollow-import-to=tools',
            '--windows-console-mode=disable',
            ('--windows-icon-from-ico=' + (Join-Path $PSScriptRoot 'assets\logo.ico')),
            '--windows-company-name=Haoxiangpao',
            '--windows-product-name=好想跑',
            '--windows-file-description=好想跑 本地工作台',
            ('--windows-file-version=' + $Version + '.0'),
            ('--windows-product-version=' + $Version + '.0'),
            ('--output-dir=' + $STAGE),
            '--output-filename=好想跑.exe',
            '--remove-output',
            (Join-Path $ROOT 'app.py')
        )
        python -m nuitka @nuitkaArgs
        if ($LASTEXITCODE -ne 0) {
            throw "Nuitka failed with exit code $LASTEXITCODE"
        }
        $distDir = Get-ChildItem -Path $STAGE -Directory -Filter '*.dist' |
            Select-Object -First 1
        if (-not $distDir) { throw "Nuitka did not produce a .dist directory" }
        Move-Item $distDir.FullName $BUILT
    } finally {
        if (Test-Path $buildInfo) { Remove-Item $buildInfo -Force }
    }
} else {
    Write-Host ('== 1/5 PyInstaller (v{0}) ==' -f $Version)
    try {
        if (Test-Path $STAGE) { Remove-Item $STAGE -Recurse -Force }
        python -m PyInstaller (Join-Path $PSScriptRoot 'build.spec') --noconfirm --clean `
            --distpath $STAGE --workpath $WORK
        if ($LASTEXITCODE -ne 0) { throw "PyInstaller failed with exit code $LASTEXITCODE" }
    } finally {
        if (Test-Path $buildInfo) { Remove-Item $buildInfo -Force }
    }
}
if (-not (Test-Path $EXE)) { throw "$Backend did not produce $EXE" }

# The native core ships next to the exe; the Python wrapper looks for
# runtime/rust/hxp-core.exe and falls back to Python when it is absent.
$runtimeRust = Join-Path $BUILT 'runtime\rust'
New-Item -ItemType Directory -Force -Path $runtimeRust | Out-Null
Copy-Item $RUST_EXE (Join-Path $runtimeRust 'hxp-core.exe') -Force
Write-Host '   bundled runtime/rust/hxp-core.exe'

$runtimeGo = Join-Path $BUILT 'runtime\go'
New-Item -ItemType Directory -Force -Path $runtimeGo | Out-Null
Copy-Item $GO_EXE (Join-Path $runtimeGo 'hxp-guard.exe') -Force
Write-Host '   bundled runtime/go/hxp-guard.exe'

# Debug symbols make function names and source paths readable; they are not
# needed on the operator's machine.
$pdbs = @(Get-ChildItem -Path $BUILT -Recurse -File -Include '*.pdb' `
    -ErrorAction SilentlyContinue)
if ($pdbs.Count -gt 0) {
    $pdbs | Remove-Item -Force
    Write-Host ('   removed {0} pdb file(s)' -f $pdbs.Count)
}

# The whole point of switching to Nuitka is not shipping Python source.  Fail
# the build if a core .py/.pyc slipped into the package (dependency data files
# such as cv2/config.py are allowed: they are not our algorithm).
Write-Host '== source leak audit =='
$leaks = @(Get-ChildItem -Path $BUILT -Recurse -File -Include '*.py', '*.pyw', '*.pyc' `
    -ErrorAction SilentlyContinue | Where-Object {
        $_.FullName -match '\\replica\\' -or $_.Name -eq 'app.py'
    })
if ($leaks.Count -gt 0) {
    throw ('refusing to package source files: ' +
           (($leaks | ForEach-Object { $_.FullName }) -join '; '))
}
Write-Host '   no replica/*.py or app.py in package'

Write-Host '== 2/5 Frozen import check =='
$check = Start-Process -FilePath $EXE -ArgumentList '--check' -Wait -PassThru
if ($check.ExitCode -ne 0) {
    throw "Frozen import check failed with exit code $($check.ExitCode)"
}

Write-Host '== 3/5 Frozen HTTP smoke test =='
$listener = [System.Net.Sockets.TcpListener]::new([Net.IPAddress]::Loopback, 0)
$listener.Start()
$port = ([System.Net.IPEndPoint]$listener.LocalEndpoint).Port
$listener.Stop()
# The developer's own copy may be running while packaging.  The single-instance
# mutex would make the smoke instance exit before it binds a port; the random
# port and staging data directory keep the two processes isolated.
$proc = Start-Process -FilePath $EXE -ArgumentList "--no-window --port $port --allow-multi" -PassThru
try {
    $ok = $false
    for ($i = 0; $i -lt 40; $i++) {
        Start-Sleep -Milliseconds 500
        try {
            $r = Invoke-WebRequest -UseBasicParsing -TimeoutSec 2 "http://127.0.0.1:$port/"
            if ($r.StatusCode -eq 200 -and $r.Content -match 'id="loginGate"') {
                $ok = $true
                break
            }
        } catch { }
    }
    if (-not $ok) { throw 'Frozen HTTP smoke test failed (no login page)' }
} finally {
    if ($proc -and -not $proc.HasExited) { Stop-Process -Id $proc.Id -Force }
}

Write-Host '== 4/5 Package =='
# The smoke test can create data/mock_rsa.*; test artifacts never ship.
$stageData = Join-Path $BUILT 'data'
if (Test-Path $stageData) { Remove-Item $stageData -Recurse -Force }
Copy-Item (Join-Path $PSScriptRoot 'USAGE.txt') (Join-Path $BUILT '使用说明.txt') -Force
if (Test-Path $ZIP) { Remove-Item $ZIP -Force }
Compress-Archive -Path (Join-Path $BUILT '*') -DestinationPath $ZIP -CompressionLevel Optimal

# Never ship a live data/ directory (tokens, receipts, device_profile.json).
Add-Type -AssemblyName System.IO.Compression.FileSystem
$zipCheck = [System.IO.Compression.ZipFile]::OpenRead($ZIP)
try {
    $entries = @($zipCheck.Entries | ForEach-Object { $_.FullName })
    if ($entries | Where-Object { $_ -like 'data/*' -or $_ -like 'data\*' }) {
        throw 'Refusing to ship: zip contains a data/ directory'
    }
    if (-not ($entries -contains '好想跑.exe')) {
        throw 'Refusing to ship: zip has no 好想跑.exe'
    }
} finally {
    $zipCheck.Dispose()
}
$HASH = Join-Path $DIST ($ARTIFACT + '_win64.sha256')
if (Test-Path $HASH) { Remove-Item $HASH -Force }
$hashValue = (Get-FileHash $ZIP -Algorithm SHA256).Hash.ToLowerInvariant()
$hashLine = $hashValue + '  ' + (Split-Path $ZIP -Leaf)
[System.IO.File]::WriteAllText(
    $HASH, $hashLine + "`r`n",
    (New-Object System.Text.UTF8Encoding($false)))

# ---- 4/5 NSIS installer -------------------------------------------------
# Release standard since v0.1.3.  NSIS is not installed permanently: point
# -Makensis at the portable makensis.exe, or unpack nsis-3.13.zip to
# app\build_tools\nsis and delete it after the build.
$setupBuilt = ''
if (-not $NoInstaller) {
    Write-Host '== 4/5 NSIS installer =='
    $maker = $Makensis
    if (-not $maker) {
        $candidates = @(
            (Join-Path $PSScriptRoot '..\build_tools\nsis\makensis.exe'),
            (Join-Path $PSScriptRoot '..\build_tools\nsis\Bin\makensis.exe')
        )
        if (${env:ProgramFiles(x86)}) {
            $candidates += (Join-Path ${env:ProgramFiles(x86)} 'NSIS\makensis.exe')
        }
        if ($env:ProgramFiles) {
            $candidates += (Join-Path $env:ProgramFiles 'NSIS\makensis.exe')
        }
        if ($env:LOCALAPPDATA) {
            $candidates += (Join-Path $env:LOCALAPPDATA 'Programs\NSIS\makensis.exe')
        }
        $maker = $candidates | Where-Object { $_ -and (Test-Path $_) } |
            Select-Object -First 1
    }
    if (-not $maker) {
        throw @'
makensis not found.

NSIS is the release standard, but it does NOT have to be installed:
  https://nsis.sourceforge.io/Download   -> download nsis-3.13.zip
  Expand it to  app\build_tools\nsis  (or anywhere)
  Pass  -Makensis <path-to-makensis.exe>
  Delete the folder after the build if you want zero footprint.

Use -NoInstaller only for a local smoke build.
'@
    }
    Write-Host ('   makensis: ' + $maker)
    # OutFile is a relative ASCII filename on purpose: makensis command-line
    # /D values are not reliably Unicode, and both this repo path and some
    # Windows profiles contain Chinese.  cwd = packaging\, so the file is
    # created next to the script either way and never travels through /D.
    $setupName = 'hxp_setup_' + [Guid]::NewGuid().ToString('N') + '.exe'
    Push-Location $PSScriptRoot
    try {
        & $maker "/DVERSION=$Version" "/DOUTFILE=$setupName" 'installer.nsi'
        if ($LASTEXITCODE -ne 0) { throw "makensis failed with exit code $LASTEXITCODE" }
    } finally {
        Pop-Location
    }
    $setupTmp = Join-Path $PSScriptRoot $setupName
    if (-not (Test-Path $setupTmp)) { throw 'makensis produced no output file' }
    if (Test-Path $SETUP) { Remove-Item $SETUP -Force }
    Move-Item $setupTmp $SETUP
    $setupHash = (Get-FileHash $SETUP -Algorithm SHA256).Hash.ToLowerInvariant()
    $setupHashFile = Join-Path $DIST ($ARTIFACT + '_win64_setup.sha256')
    [System.IO.File]::WriteAllText(
        $setupHashFile,
        ($setupHash + '  ' + (Split-Path $SETUP -Leaf) + "`r`n"),
        (New-Object System.Text.UTF8Encoding($false)))
    $setupBuilt = $SETUP
    Write-Host ('   安装包: {0} ({1:N1} MB)' -f $SETUP,
        ((Get-Item $SETUP).Length / 1MB))
} else {
    Write-Host '== 4/5 NSIS installer skipped (-NoInstaller) =='
}

Write-Host '== latest.json (auto-update manifest) =='
$makeLatest = Join-Path $PSScriptRoot 'make_latest.py'
$latestArgs = @($makeLatest, '--dist', $DIST, '--version', $Version,
                '--channel', $Channel,
                '--rollback-version', $RollbackVersion)
if ($DownloadBaseUrl) {
    $latestArgs += @('--base-url', $DownloadBaseUrl)
}
foreach ($mirror in $MirrorBaseUrl) {
    if ($mirror) { $latestArgs += @('--mirror-base-url', $mirror) }
}
if ($RollbackBaseUrl) {
    $latestArgs += @('--rollback-base-url', $RollbackBaseUrl)
}
foreach ($mirror in $RollbackMirrorBaseUrl) {
    if ($mirror) { $latestArgs += @('--rollback-mirror-base-url', $mirror) }
}
if ($setupBuilt) {
    $latestArgs += @('--setup', $setupBuilt)
}
& python @latestArgs
if ($LASTEXITCODE -ne 0) {
    throw "latest.json generation failed with exit code $LASTEXITCODE"
}
# github-release/ is the publishing folder committed to the repo; keep its
# manifest in sync with the artifact that was just built.
$ghDir = Join-Path (Split-Path $ROOT -Parent) 'github-release'
if (Test-Path $ghDir) {
    Copy-Item (Join-Path $DIST 'latest.json') (Join-Path $ghDir 'latest.json') -Force
    Write-Host ('   synced: ' + (Join-Path $ghDir 'latest.json'))
}

Write-Host '== 5/5 Install (preserve live data) =='
# If rebuilding the same version, move its data aside before replacing the
# binaries, then put it back.  The archive above was built without it.
$backup = Join-Path $ROOT ('build_target_backup_' + [Guid]::NewGuid().ToString('N'))
$hasBackup = $false
if (Test-Path $TARGET) {
    $oldData = Join-Path $TARGET 'data'
    if (Test-Path $oldData) {
        New-Item -ItemType Directory -Path $backup | Out-Null
        Move-Item $oldData (Join-Path $backup 'data')
        $hasBackup = $true
    }
    Remove-Item $TARGET -Recurse -Force
}
Copy-Item -Path $BUILT -Destination $TARGET -Recurse -Force
if ($hasBackup) {
    Move-Item (Join-Path $backup 'data') (Join-Path $TARGET 'data')
    Remove-Item $backup -Recurse -Force
}

# A new version directory starts empty.  Carry the live data over from the
# newest existing version (or -MigrateDataFrom) so the operator stays logged
# in and the receipt/daily guards keep their state.  The zip was built above,
# so data/ can never enter it.
$targetData = Join-Path $TARGET 'data'
if (-not $NoDataMigration -and -not (Test-Path $targetData)) {
    $sourceData = $null
    if ($MigrateDataFrom) {
        $candidate = if (Test-Path (Join-Path $MigrateDataFrom 'data')) {
            Join-Path $MigrateDataFrom 'data'
        } else {
            $MigrateDataFrom
        }
        if (Test-Path $candidate) {
            $sourceData = $candidate
        } else {
            Write-Warning "MigrateDataFrom has no data/: $MigrateDataFrom"
        }
    } else {
        $candidates = @(Get-ChildItem -Path $DIST -Directory -Filter '好想跑_v*' -ErrorAction SilentlyContinue |
            Where-Object { $_.FullName -ne $TARGET -and (Test-Path (Join-Path $_.FullName 'data')) } |
            Sort-Object { try { [version]($_.Name -replace '^好想跑_v', '') } catch { [version]'0.0.0' } } -Descending)
        if ($candidates.Count -gt 0) {
            $sourceData = Join-Path $candidates[0].FullName 'data'
        }
    }
    if ($sourceData) {
        Write-Host ('== data migration: ' + (Split-Path (Split-Path $sourceData -Parent) -Leaf) + ' ==')
        try {
            & (Join-Path $PSScriptRoot 'migrate_data.ps1') -From $sourceData -To $targetData `
                -BackupRoot (Join-Path $ROOT 'backup')
        } catch {
            Write-Warning ('data migration failed: ' + $_.Exception.Message)
            Write-Warning 'the new build starts logged out; copy data/ manually from the previous version'
        }
    } else {
        Write-Host '== data migration: no previous version found (clean install) =='
    }
}

if (Test-Path $STAGE) { Remove-Item $STAGE -Recurse -Force }
if (Test-Path $WORK) { Remove-Item $WORK -Recurse -Force }

$size = (Get-ChildItem $TARGET -Recurse -File | Measure-Object Length -Sum).Sum / 1MB
Write-Host ('完成: {0}' -f (Join-Path $TARGET '好想跑.exe'))
Write-Host ('压缩包: {0}' -f $ZIP)
if ($setupBuilt) { Write-Host ('安装包: {0}' -f $setupBuilt) }
Write-Host ('总体积: {0:N1} MB' -f $size)
Write-Host '旧 dist/好想跑/ 未改动；本次版本目录的 data/ 已保留（同版本重建）或从旧版本迁移。'
